import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Lists every {@code -D} option of the Loader in {@code docs/OPTIONS.md}, from the Javadoc of the
 * {@code *Options} classes: each Javadoc block that starts with {@code {@code -Dname=...}} is one
 * option. The same format as the Bridge's list.
 *
 * <p>Usage: {@code Options <source dir> <docs/OPTIONS.md> [--check]}. With {@code --check} it
 * writes nothing and fails when the file is out of date ({@code ./gradlew build} runs it that way;
 * {@code ./gradlew options} rewrites the file).
 */
public final class Options {

    private static final Pattern JAVADOC = Pattern.compile("/\\*\\*(.*?)\\*/", Pattern.DOTALL);

    private Options() {}

    public static void main(String[] args) throws IOException {
        Path src = Paths.get(args[0]);
        Path out = Paths.get(args[1]);
        boolean check = args.length > 2 && args[2].equals("--check");
        String text = generate(src);
        if (check) {
            String current =
                    Files.isRegularFile(out)
                            ? Files.readString(out, StandardCharsets.UTF_8).replace("\r\n", "\n")
                            : "";
            if (!current.equals(text)) {
                System.err.println(out + " is out of date: run ./gradlew options");
                System.exit(1);
            }
            System.out.println(out + " is up to date");
            return;
        }
        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.writeString(out, text, StandardCharsets.UTF_8);
        System.out.println(
                out + ": " + text.lines().filter(l -> l.startsWith("- ")).count() + " options");
    }

    private static String generate(Path src) throws IOException {
        List<Path> files;
        try (Stream<Path> s = Files.walk(src)) {
            files =
                    s.filter(p -> p.getFileName().toString().endsWith("Options.java"))
                            .sorted()
                            .toList();
        }
        StringBuilder b = new StringBuilder();
        b.append("# Stein Loader options\n\n");
        b.append("Every `-D` option the Loader reads, generated by `tools/Options.java`")
                .append(" (`./gradlew options`) from the `*Options` classes.\n");
        b.append("Pass them to the JVM (`./gradlew runClient -Pstein.jvmArgs=\"-D...\"`).")
                .append(" Most are for testing; players never need them.\n");
        b.append(
                        "The Bridge's options are in its own `docs/OPTIONS.md`; the mod API reads one more,")
                .append(
                        " `-Dstein.debug=modid|all|id1,id2`, which turns on a mod's `Log.debug`.\n");
        for (Path f : files) {
            Matcher m = JAVADOC.matcher(Files.readString(f, StandardCharsets.UTF_8));
            List<String> options = new ArrayList<>();
            while (m.find()) {
                String doc = oneLine(m.group(1));
                if (doc.startsWith("{@code -D")) {
                    options.add("- " + markdown(doc));
                }
            }
            if (options.isEmpty()) {
                continue; // a class named *Options that holds no -D option (the HUD's settings)
            }
            String cls = f.getFileName().toString().replace(".java", "");
            String pkg =
                    src.relativize(f.getParent()).toString().replace('\\', '.').replace('/', '.');
            b.append("\n## ").append(cls).append("\n\n");
            b.append('`').append(pkg).append('.').append(cls).append("`\n\n");
            for (String o : options) {
                b.append(o).append('\n');
            }
        }
        return b.toString();
    }

    /** The block without the leading stars, in one line. */
    private static String oneLine(String block) {
        StringBuilder b = new StringBuilder();
        for (String line : block.split("\r?\n")) {
            b.append(' ').append(line.replaceFirst("^\\s*\\*?\\s?", "").trim());
        }
        return b.toString().trim().replaceAll("\\s+", " ");
    }

    /** {@code {@code x}} and {@code {@link x}} become {@code `x`}. */
    private static String markdown(String doc) {
        return doc.replaceAll("\\{@(?:code|link) ([^}]*)\\}", "`$1`");
    }
}
